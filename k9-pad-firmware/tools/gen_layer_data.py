MAX_LAYERS = 10


def fmt_row(data: list[int], indent: str = "        ") -> str:
    """Format 30 bytes as a C hex row."""
    return indent + ", ".join(f"0x{b:02X}" for b in data)


def gen_icon_array(n: int) -> str:
    """Generate layer_digit_icons[NUM_LAYERS] C array."""
    if n > MAX_LAYERS:
        print(f"ERROR: max {MAX_LAYERS} layers supported (digit icons 0-9)", file=sys.stderr)
        sys.exit(1)
    lines = []
    lines.append(f"//--------数字图标查找表 (30x30, gen_layer_data.py 生成，与 NUM_LAYERS 同步)")
    lines.append(f"// 每个图标 120 bytes (30×4 rows), 运行时由 WouoUI_UserInit 复制到 main_icon_storage")
    lines.append(f"// 增加 Layer 时用 tools/gen_layer_data.py 重新生成此数组")
    lines.append(f"static const Icon layer_digit_icons[NUM_LAYERS] = {{")
    for i in range(n):
        data = DIGIT_ICONS[i]
        lines.append(f"    // [{i}] digit \"{i}\"")
        lines.append(f"    {{")
        for row in range(4):
            start = row * 30
            comma = "," if (row < 3 or i < n - 1) else ""
            # Last byte of last row of last icon: no trailing comma after }
            lines.append(fmt_row(data[start:start + 30]) + ("," if row < 3 else ""))
        lines.append(f"    }},") if i < n - 1 else lines.append(f"    }}")
    lines.append(f"}};")
    return "\n".join(lines)


def gen_text_arrays(n: int) -> str:
    """Generate main_layer_texts, pad_titles, features_layer_texts."""
    lines = []

    # main_layer_texts
    lines.append(f"//--------文本查找表 (gen_layer_data.py 生成，与 NUM_LAYERS 同步)")
    entries = [f'(char*)"+ Layer {i}"' for i in range(n)]
    lines.append(f"static char* main_layer_texts[NUM_LAYERS] = {{")
    # Wrap at ~3 per line
    for start in range(0, n, 3):
        chunk = entries[start:start + 3]
        sep = "," if start + 3 < n else ""
        lines.append(f"    {', '.join(chunk)}{sep}")
    lines.append(f"}};")
    lines.append("")

    # pad_titles
    lines.append(f"//--------Layer 子页面选项文本查找表 (gen_layer_data.py 生成，与 NUM_LAYERS 同步)")
    entries = [f'(char*)"- Layer {i}"' for i in range(n)]
    lines.append(f"static char* pad_titles[NUM_LAYERS] = {{")
    for start in range(0, n, 3):
        chunk = entries[start:start + 3]
        sep = "," if start + 3 < n else ""
        lines.append(f"    {', '.join(chunk)}{sep}")
    lines.append(f"}};")

    # features_layer_texts
    entries = [f'(char*)"! Layer {i}"' for i in range(n)]
    lines.append(f"static char* features_layer_texts[NUM_LAYERS] = {{")
    for start in range(0, n, 3):
        chunk = entries[start:start + 3]
        sep = "," if start + 3 < n else ""
        lines.append(f"    {', '.join(chunk)}{sep}")
    lines.append(f"}};")

    return "\n".join(lines)


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    if n < 1 or n > MAX_LAYERS:
        print(f"NUM_LAYERS must be 1..{MAX_LAYERS}", file=sys.stderr)
        sys.exit(1)

    print(f"// Generated by gen_layer_data.py for NUM_LAYERS={n}")
    print(f"// Paste these blocks into WouoUI_k9pad.c, replacing the existing ones.")
    print(f"// Also update: #define NUM_LAYERS {n}  (WouoUI_k9pad.c)")
    print(f"//              pub const NUM_LAYERS: u8 = {n};  (mode.rs)")
    print()
    print(gen_icon_array(n))
    print()
    print(gen_text_arrays(n))


if __name__ == "__main__":
    main()
